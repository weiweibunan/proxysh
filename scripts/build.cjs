// Generate the standalone installer; users need only argosbx.sh.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const parts = ['src/header.sh', 'lib/releases.sh', 'lib/routing.sh', 'lib/runtime.sh'];
let output = parts.map(p => `\n# ---- ${p} ----\n${fs.readFileSync(path.join(root, p), 'utf8').replace(/\r\n/g, '\n')}`).join('');
output = '#!/usr/bin/env bash\n# SPDX-License-Identifier: GPL-3.0-only\n# Generated by node scripts/build.cjs. Source: https://github.com/weiweibunan/proxysh\n' + output;
output += '\nagsbx_legacy_main() {\n' + fs.readFileSync(path.join(root, 'src/legacy.sh'), 'utf8').replace(/^#![^\n]*\n/, '').replace(/\r\n/g, '\n') + '\n}\n';
output += '\nif [[ ${AGSBX_SOURCE_ONLY:-0} != 1 ]]; then\n    agsbx_main "$@"\nfi\n';
const target = path.join(root, 'argosbx.sh');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) { process.stderr.write('argosbx.sh is out of date\n'); process.exit(1); }
} else fs.writeFileSync(target, output);
